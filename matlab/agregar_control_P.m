function agregar_control_P(modelo)
% Autor: GR09, Integrante 1 (completar nombre).
% Proposito: dibujar el mismo controlador en los dos modelos.
% Entrada: nombre del modelo abierto. Salida: bloques y conexiones comunes.
% Esta automatizacion es opcional; la guia explica como dibujarla a mano.
add_block('simulink/Sources/Step',[modelo '/Referencia'], ...
    'Time','instante_ref','Before','r_antes','After','r_despues', ...
    'Position',[20 -300 70 -270]);
add_block('simulink/Sources/From Workspace',[modelo '/Ruido'], ...
    'VariableName','senal_ruido','Interpolate','off', ...
    'OutputAfterFinalValue','Holding final value', ...
    'Position',[20 -180 120 -150]);
add_block('simulink/Math Operations/Sum',[modelo '/Medicion'], ...
    'Inputs','++','Position',[170 -220 200 -180]);
add_block('simulink/Math Operations/Sum',[modelo '/Error'], ...
    'Inputs','+-','Position',[260 -290 290 -250]);
add_block('simulink/Math Operations/Gain',[modelo '/Kp'], ...
    'Gain','Kp','Position',[340 -290 400 -250]);
add_block('simulink/Math Operations/Bias',[modelo '/I_equilibrio'], ...
    'Bias','I0','Position',[445 -290 510 -250]);
add_block('simulink/Discontinuities/Saturation',[modelo '/Limite_I'], ...
    'UpperLimit','Imax','LowerLimit','Imin','Position',[555 -290 620 -250]);
add_block('simulink/Continuous/State-Space',[modelo '/Dinamica_corriente'], ...
    'A','-1/tau_corriente','B','1/tau_corriente','C','1','D','0', ...
    'X0','I0','Position',[660 -450 790 -405]);
add_block('simulink/Sources/From Workspace',[modelo '/Carga'], ...
    'VariableName','senal_carga','Interpolate','off', ...
    'OutputAfterFinalValue','Holding final value', ...
    'Position',[20 -80 120 -50]);
add_block('simulink/Math Operations/Bias',[modelo '/Tb_C'], ...
    'Bias','-273.15','Position',[1090 -220 1170 -180]);
add_block('simulink/Sinks/To Workspace',[modelo '/Guardar_Tb'], ...
    'VariableName','Tb','SaveFormat','Timeseries','MaxDataPoints','inf', ...
    'Position',[1250 -220 1350 -185]);
add_block('simulink/Sinks/To Workspace',[modelo '/Guardar_ref'], ...
    'VariableName','referencia','SaveFormat','Timeseries','MaxDataPoints','inf', ...
    'Position',[120 -355 230 -320]);
add_block('simulink/Math Operations/Product',[modelo '/Potencia'], ...
    'Position',[1090 -100 1130 -60]);
add_block('simulink/Sinks/To Workspace',[modelo '/Guardar_P'], ...
    'VariableName','P_electrica','SaveFormat','Timeseries','MaxDataPoints','inf', ...
    'Position',[1250 -100 1350 -65]);
add_line(modelo,'Ruido/1','Medicion/2','autorouting','on');
add_line(modelo,'Tb_C/1','Medicion/1','autorouting','on');
add_line(modelo,'Medicion/1','Error/1','autorouting','on');
add_line(modelo,'Referencia/1','Error/2','autorouting','on');
add_line(modelo,'Error/1','Kp/1','autorouting','on');
add_line(modelo,'Kp/1','I_equilibrio/1','autorouting','on');
add_line(modelo,'I_equilibrio/1','Limite_I/1','autorouting','on');
add_line(modelo,'Limite_I/1','Dinamica_corriente/1','autorouting','on');
add_line(modelo,'Tb_C/1','Guardar_Tb/1','autorouting','on');
add_line(modelo,'Referencia/1','Guardar_ref/1','autorouting','on');
add_line(modelo,'Potencia/1','Guardar_P/1','autorouting','on');
set_param(modelo,'Solver','ode23t','StopTime','t_final', ...
    'MaxStep','0.2','RelTol','1e-6','AbsTol','1e-8', ...
    'ReturnWorkspaceOutputs','on');
set_param(modelo,'Description', ...
    'GR09 - P. e=Tb_medida-ref; mando=sat(I0+Kp*e,0,2); tau*dI/dt=mando-I.');
end
